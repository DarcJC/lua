/*
** lua2llvmir.c - Convert Lua source code to LLVM IR
** This tool compiles Lua 5.4 source code to bytecode and then generates LLVM IR
*/

#define LUA_CORE

#include "lprefix.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "lua.h"
#include "lauxlib.h"
#include "ldebug.h"
#include "lobject.h"
